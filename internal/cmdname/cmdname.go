package cmdname

// Name 返回已知协议号中文说明（未知返回空，便于日志拼接）。
func Name(cmd int32) string {
	if n, ok := names[cmd]; ok {
		return n
	}
	return ""
}

// Format 形如 "1001 LOGIN_IN" 或 "9999(未收录)"。
func Format(cmd int32) string {
	if n, ok := names[cmd]; ok {
		return fmtCmd(cmd, n)
	}
	return fmtCmd(cmd, "未收录")
}

func fmtCmd(cmd int32, name string) string {
	return itoa(cmd) + " " + name
}

func itoa(n int32) string {
	if n == 0 {
		return "0"
	}
	neg := n < 0
	if neg {
		n = -n
	}
	var b [12]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	if neg {
		i--
		b[i] = '-'
	}
	return string(b[i:])
}

